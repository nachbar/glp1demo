// Computes CSP hashes for the inline <style> and <script> blocks in index.html
// and rewrites netlify.toml. Run before every deploy: node tools/build-csp.mjs
import { readFileSync, writeFileSync } from 'fs';
import { createHash } from 'crypto';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');
const sha = s => "'sha256-" + createHash('sha256').update(s, 'utf8').digest('base64') + "'";
const blocks = (tag) => [...html.matchAll(new RegExp(`<${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</${tag}>`, 'g'))].map(m => m[1]);
const styles = blocks('style'), scripts = blocks('script');
if (!styles.length || !scripts.length) throw new Error('no inline style/script block found');

const csp = [
  "default-src 'none'",
  `script-src ${scripts.map(sha).join(' ')}`,
  `style-src ${styles.map(sha).join(' ')}`,
  "img-src 'self' data:",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');

const toml = `# Generated by tools/build-csp.mjs - do not edit the CSP line by hand.
[build]
  publish = "."

[[headers]]
  for = "/*"
  [headers.values]
    Content-Security-Policy = "${csp}"
    X-Frame-Options = "DENY"
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "no-referrer"
    Permissions-Policy = "camera=(), microphone=(), geolocation=()"
`;
writeFileSync(join(root, 'netlify.toml'), toml);
console.log('netlify.toml updated:', scripts.length, 'script hash(es),', styles.length, 'style hash(es)');
